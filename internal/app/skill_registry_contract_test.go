// Run the public dispatcher in a separate process with an isolated home. This
// mirrors main's exit/error contract without building a second CLI in tests.
func TestSkillRegistryCLIProcess(t *testing.T) {
	if os.Getenv("SKILL_REGISTRY_TEST_PROCESS") != "1" {
		return
	}
	home := os.Getenv("SKILL_REGISTRY_TEST_HOME")
	if err := os.Setenv("HOME", home); err != nil {
		panic(err)
	}
	if err := os.Setenv("USERPROFILE", home); err != nil {
		panic(err)
	}
	for i, arg := range os.Args {
		if arg == "--" {
			if err := RunArgs(os.Args[i+1:], os.Stdout); err != nil {
				fmt.Fprintf(os.Stderr, "Error: %v\n", err)
				os.Exit(1)
			}
			os.Exit(0)
		}
	}
	os.Exit(2)
}

type registryCommandResult struct {
	code           int
	stdout, stderr string
}

func registryCommand(t *testing.T, home string, args ...string) registryCommandResult {
	t.Helper()
	return registryCommandAt(t, home, "", "", args...)
}

func registryCommandAt(t *testing.T, home, cwd, codexHome string, args ...string) registryCommandResult {
	t.Helper()
	cmd := exec.Command(os.Args[0], append([]string{"-test.run=^TestSkillRegistryCLIProcess$", "--", "skill-registry"}, args...)...)
	cmd.Dir = cwd
	cmd.Env = []string{
		"SKILL_REGISTRY_TEST_PROCESS=1", "SKILL_REGISTRY_TEST_HOME=" + home,
		"HOME=" + home, "USERPROFILE=" + home, "CODEX_HOME=" + codexHome, "TMPDIR=" + t.TempDir(),
		"GOMODCACHE=" + os.Getenv("GOMODCACHE"), "GOCACHE=" + os.Getenv("GOCACHE"),
		"SystemRoot=" + os.Getenv("SystemRoot"),
	}
	var stdout, stderr bytes.Buffer
	cmd.Stdout, cmd.Stderr = &stdout, &stderr
	err := cmd.Run()
	code := 0
	if err != nil {
		if exit, ok := err.(*exec.ExitError); ok {
			code = exit.ExitCode()
		} else {
			t.Fatalf("run skill-registry: %v", err)
		}
	}
	return registryCommandResult{code, stdout.String(), stderr.String()}
}

func assertRegistryCommand(t *testing.T, got registryCommandResult, code int, stdout, stderr string) {
	t.Helper()
	if got.code != code || got.stdout != stdout || got.stderr != stderr {
		t.Fatalf("command = exit %d, stdout %q, stderr %q; want exit %d, stdout %q, stderr %q", got.code, got.stdout, got.stderr, code, stdout, stderr)
	}
}

func registryFixture(t *testing.T) (project, home string) {
	t.Helper()
	project, home = t.TempDir(), t.TempDir()
	if err := os.Mkdir(filepath.Join(project, ".git"), 0o755); err != nil {
		t.Fatal(err)
	}
	return project, home
}

func registryRead(t *testing.T, path string) string {
	t.Helper()
	data, err := os.ReadFile(path)
	if err != nil {
		t.Fatal(err)
	}
	return string(data)
}

func TestSkillRegistrySharedBytes(t *testing.T) {
	project, home := registryFixture(t)
	skill := filepath.Join(project, "skills", "demo", "SKILL.md")
	writeSkillFile(t, skill, "---\r\nname: demo\r\ndescription: 'a | b'\r\n---\r\nignored body\r\n")
	registry := filepath.Join(project, ".atl", "skill-registry.md")
	assertRegistryCommand(t, registryCommand(t, home, "refresh", "--no-gitignore", "--cwd", project), 0,
		fmt.Sprintf("Skill registry refreshed (1 skills): %s\n", registry), "")
	want := fmt.Sprintf("# Skill Registry — %s\n\n"+
		"<!-- Shared disk skill registry; generated by Gentle Shell or Gentle AI. -->\n\n"+
		"## Sources scanned\n\n- skills\n\n"+
		"## Contract\n\n"+
		"**Delegator use only.** This disk index is not a summary and excludes session-only runtime skills. Pi delegators use their effective session view; other delegators use these rows. Pass exact `SKILL.md` paths to subagents.\n\n"+
		"`SKILL.md` remains the source of truth. Do not inject generated summaries or compact rules by default; pass paths so subagents load the full runtime contract and preserve author intent.\n\n"+
		"## Skills\n\n| Skill | Trigger / description | Scope | Path |\n| --- | --- | --- | --- |\n"+
		"| `demo` | a \\| b | project | `%s` |\n\n"+
		"## Loading protocol\n\n"+
		"1. Match task context and target files against the effective view's `Trigger / description` column.\n"+
		"2. Pass only the matching `Path` values to the subagent under `## Skills to load before work`.\n"+
		"3. Instruct the subagent to read those exact `SKILL.md` files before reading, writing, reviewing, testing, or creating artifacts.\n"+
		"4. If no matching skill exists, proceed without project skill injection and report `skill_resolution: none`.\n", filepath.Base(project), skill)
	if got := registryRead(t, registry); got != want {
		t.Errorf("registry bytes differ:\ngot:\n%s\nwant:\n%s", got, want)
	}
	sum := sha256.Sum256([]byte(want))
	wantCache := fmt.Sprintf("{\"schema\":1,\"registry_sha256\":\"%x\"}\n", sum)
	if got := registryRead(t, filepath.Join(project, ".atl", ".skill-registry.cache.json")); got != wantCache {
		t.Errorf("cache = %q, want %q", got, wantCache)
	}
}

func TestSkillRegistryUnchangedForceAndBodyAreNoOps(t *testing.T) {
	project, home := registryFixture(t)
	skill := filepath.Join(project, "skills", "demo", "SKILL.md")
	writeSkillFile(t, skill, "---\nname: demo\ndescription: same\n---\nold body\n")
	registry := filepath.Join(project, ".atl", "skill-registry.md")
	cache := filepath.Join(project, ".atl", ".skill-registry.cache.json")
	assertRegistryCommand(t, registryCommand(t, home, "refresh", "--quiet", "--no-gitignore", "--cwd", project), 0, "", "")
	old := time.Unix(1000000000, 0)
	for _, path := range []string{registry, cache} {
		if err := os.Chtimes(path, old, old); err != nil {
			t.Fatal(err)
		}
	}
	writeSkillFile(t, skill, "---\nname: demo\ndescription: same\n---\nnew body\n")
	for _, args := range [][]string{{"refresh", "--no-gitignore", "--cwd", project}, {"refresh", "--force", "--no-gitignore", "--cwd", project}} {
		assertRegistryCommand(t, registryCommand(t, home, args...), 0, fmt.Sprintf("Skill registry up to date (unchanged): %s\n", registry), "")
		for _, path := range []string{registry, cache} {
			info, err := os.Stat(path)
			if err != nil || !info.ModTime().Equal(old) {
				t.Fatalf("unchanged %s modified: %v %v", path, info, err)
			}
		}
	}
}

func TestSkillRegistryRepairsLegacyCacheAndTamperedRegistry(t *testing.T) {
	project, home := registryFixture(t)
	writeSkillFile(t, filepath.Join(project, "skills", "demo", "SKILL.md"), "---\nname: demo\ndescription: first\n---\n")
	args := []string{"refresh", "--quiet", "--no-gitignore", "--cwd", project}
	assertRegistryCommand(t, registryCommand(t, home, args...), 0, "", "")
	registry := filepath.Join(project, ".atl", "skill-registry.md")
	cache := filepath.Join(project, ".atl", ".skill-registry.cache.json")
	original := registryRead(t, registry)
	for _, legacy := range []string{"{\"fingerprint\":\"old-go\"}\n", "{\"schema\":9,\"fingerprint\":\"old-pi\"}\n", "not json", ""} {
		if err := os.WriteFile(cache, []byte(legacy), 0o600); err != nil {
			t.Fatal(err)
		}
		assertRegistryCommand(t, registryCommand(t, home, args...), 0, "", "")
		sum := sha256.Sum256([]byte(original))
		if got, want := registryRead(t, cache), fmt.Sprintf("{\"schema\":1,\"registry_sha256\":\"%x\"}\n", sum); got != want {
			t.Errorf("repair of %q: got %q, want %q", legacy, got, want)
		}
	}
	if err := os.WriteFile(registry, []byte("tampered\n"), 0o600); err != nil {
		t.Fatal(err)
	}
	assertRegistryCommand(t, registryCommand(t, home, args...), 0, "", "")
	if got := registryRead(t, registry); got != original {
		t.Fatalf("registry not repaired: %q", got)
	}
}


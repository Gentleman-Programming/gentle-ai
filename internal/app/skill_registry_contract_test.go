func TestSkillRegistryOrdersFullCandidatePaths(t *testing.T) {
	cases := []struct {
		name, loser, winner string
	}{
		{"direct skills", "foo/SKILL.md", "foo-bar/SKILL.md"},
		{"category prefixes", "foo/item/SKILL.md", "foo-bar/item/SKILL.md"},
		{"nested skill prefixes", "category/foo/SKILL.md", "category/foo-bar/SKILL.md"},
	}
	for _, tc := range cases {
		t.Run(tc.name, func(t *testing.T) {
			project, home := registryFixture(t)
			root := filepath.Join(project, "skills")
			loser := filepath.Join(root, filepath.FromSlash(tc.loser))
			winner := filepath.Join(root, filepath.FromSlash(tc.winner))
			writeSkillFile(t, loser, "---\nname: duplicate\ndescription: later path\n---\n")
			writeSkillFile(t, winner, "---\nname: duplicate\ndescription: earlier path\n---\n")
			t.Run("list", func(t *testing.T) {
				rows := []registryRow{{"duplicate", "project", "earlier path", winner}}
				want, err := json.MarshalIndent(rows, "", "  ")
				if err != nil {
					t.Fatal(err)
				}
				assertRegistryCommand(t, registryCommand(t, home, "list", "--json", "--cwd", project), 0, string(want)+"\n", "")
			})
			t.Run("refresh", func(t *testing.T) {
				registry := filepath.Join(project, ".atl", "skill-registry.md")
				assertRegistryCommand(t, registryCommand(t, home, "refresh", "--no-gitignore", "--cwd", project), 0,
					fmt.Sprintf("Skill registry refreshed (1 skills): %s\n", registry), "")
				got := registryRead(t, registry)
				want := fmt.Sprintf("| `duplicate` | earlier path | project | `%s` |", winner)
				if !strings.Contains(got, want) || strings.Contains(got, loser) {
					t.Fatalf("registry did not select earlier full path %q:\n%s", winner, got)
				}
			})
		})
	}
}

